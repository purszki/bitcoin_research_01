const uint64_t siphash_k0 = 0xd37ef974b301eb9fULL;
const uint64_t siphash_k1 = 0xd40576aa884a7130ULL;

// Number of timing iterations for stable results.
static constexpr int ITERATIONS = 1000;

int main()
{
    // --- Parse wallet scripts ---
    GCSFilter::ElementSet wallet_elements;
    Fuse16Filter::ElementSet wallet_elements_fuse;
    for (const auto& hex : wallet_script_hexes) {
        auto bytes = ParseHex(hex);
        wallet_elements.emplace(bytes.begin(), bytes.end());
        wallet_elements_fuse.emplace(bytes.begin(), bytes.end());
    }

    // --- Parse block hash for SipHash keys ---
    const uint256 block_hash = uint256::FromHex(block_hash_hex).value();
    const uint64_t k0 = block_hash.GetUint64(0);
    const uint64_t k1 = block_hash.GetUint64(1);

    // --- Parse filter bytes ---
    const std::vector<unsigned char> gcs_bytes = ParseHex(gcs_filter_hex);
    const std::vector<unsigned char> fuse16_bytes = ParseHex(fuse16_filter_hex);

    std::cout << "=== GCS vs Fuse16 Filter Demo ===\n\n";
    std::cout << "Block: " << block_hash_hex << "\n";
    std::cout << "Block elements: " << block_element_count << "\n";
    std::cout << "Wallet scripts: " << wallet_script_hexes.size() << "\n\n";

    std::cout << "Filter sizes:\n";
    std::cout << "  GCS (BIP 158):   " << gcs_bytes.size() << " bytes ("
              << std::fixed << std::setprecision(2)
              << (gcs_bytes.size() * 8.0 / block_element_count) << " bits/element)\n";
    std::cout << "  Binary Fuse16:   " << fuse16_bytes.size() << " bytes ("
              << std::fixed << std::setprecision(2)
              << (fuse16_bytes.size() * 8.0 / block_element_count) << " bits/element)\n";
    std::cout << "  Size difference: " << std::showpos
              << static_cast<int>(fuse16_bytes.size()) - static_cast<int>(gcs_bytes.size())
              << " bytes (" << std::noshowpos << std::fixed << std::setprecision(1)
              << (100.0 * fuse16_bytes.size() / gcs_bytes.size() - 100.0) << "%)\n\n";

    // --- Benchmark GCS: deserialize + MatchAny ---
    double gcs_us = 0;
    {
        bool match = false;
        auto start = std::chrono::high_resolution_clock::now();
        for (int i = 0; i < ITERATIONS; ++i) {
            GCSFilter::Params params(k0, k1, BASIC_FILTER_P, BASIC_FILTER_M);
            GCSFilter filter(params, gcs_bytes, /*skip_decode_check=*/false);
            match = filter.MatchAny(wallet_elements);
        }
        auto end = std::chrono::high_resolution_clock::now();
        auto ns = std::chrono::duration_cast<std::chrono::nanoseconds>(end - start).count();
        gcs_us = ns / 1000.0 / ITERATIONS;

        std::cout << "GCS (BIP 158) — deserialize + MatchAny:\n";
        std::cout << "  Result:  " << (match ? "MATCH" : "no match") << "\n";
        std::cout << "  Time:    " << std::fixed << std::setprecision(1)
                  << gcs_us << " µs/query"
                  << "  (" << ITERATIONS << " iterations)\n\n";
    }

    // --- Benchmark Fuse16: deserialize + MatchAny ---
    double fuse_us = 0;
    {
        bool match = false;
        auto start = std::chrono::high_resolution_clock::now();
        for (int i = 0; i < ITERATIONS; ++i) {
            Fuse16Filter filter = Fuse16Filter::Deserialize(k0, k1, fuse16_bytes);
            match = filter.MatchAny(wallet_elements_fuse);
        }
        auto end = std::chrono::high_resolution_clock::now();
        auto ns = std::chrono::duration_cast<std::chrono::nanoseconds>(end - start).count();
        fuse_us = ns / 1000.0 / ITERATIONS;

        std::cout << "Binary Fuse16 — deserialize + MatchAny:\n";
        std::cout << "  Result:  " << (match ? "MATCH" : "no match") << "\n";
        std::cout << "  Time:    " << std::fixed << std::setprecision(1)
                  << fuse_us << " µs/query"
                  << "  (" << ITERATIONS << " iterations)\n\n";
    }

    std::cout << "Speedup: Fuse16 is " << std::fixed << std::setprecision(0)
              << (gcs_us / fuse_us) << "x faster than GCS\n";

    return 0;
}
